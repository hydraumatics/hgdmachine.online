// Writes EMAILS.md: a readable copy of every email the website sends, built from server/emails.js.
//   bun run emails
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { newsletterConfirmation, quoteAcknowledgement, quoteNotification } from "../server/emails.js";

const quote = { ref: "HYD-261122-A1B2C3", name: "Ada Mwansa, Procurement Officer", company: "Kansanshi Contractors", email: "ada@example.com", phone: "+260 97 000 0000",
  delivery: "CIF Ndola", urgency: "Urgent: machine down", details: "2 x hydraulic pump for Komatsu PC400-7\nPart number 708-2L-00300\nNeeded at Kitwe depot this week." };

const block = (text) => `\`\`\`text\n${text}\n\`\`\``;
const mail = (title, when, to, m) => `## ${title}\n\n- **Sent:** ${when}\n- **To:** ${to}\n- **Subject:** ${m.subject}\n\n${block(m.text)}\n`;

export function render() {
  const ack = quoteAcknowledgement(quote);
  const staff = quoteNotification(quote);
  const confirm = newsletterConfirmation({ name: "Ada", link: "https://hgdmachines.online/api/newsletter/confirm?t=0123456789abcdef" });
  return [
    "# Emails the website sends",
    "",
    "Generated from `server/emails.js` with `bun run emails`. Do not edit this file by hand: change the wording in `server/emails.js`, run the command, commit both.",
    "The examples use made-up customer data. Customer emails also have an HTML version with the same words, a navy header, a highlighted reference and a gold button.",
    "Emails to customers and subscribers are only sent when `RESEND_API_KEY` and `MAIL_FROM` are set. The team notification also works with `WEB3FORMS_KEY`.",
    "",
    mail("1. Quote request: confirmation to the customer", "right after the customer sends the quote form (needs Resend)", "the customer", ack),
    mail("2. Quote request: notification to our team", "right after the form is sent", "procurement@hgdmachines.online (or `STAFF_EMAIL`), reply goes to the customer", staff),
    mail("3. Newsletter: confirm your subscription", "after the newsletter form, when Resend is set up (double opt-in)", "the subscriber", confirm),
    "## 4. Newsletter: signup note to our team",
    "",
    "- **Sent:** after the newsletter form, when Resend is not set up (single opt-in), or when the database is missing",
    "- **To:** news@hgdmachines.online",
    "- **Subject:** Newsletter signup",
    "",
    block("Email: ada@example.com\nName: Ada\nInterests: Spare parts, Safety supplies\nConsent given on 2026-11-22T10:00:00.000Z to: \"Send me the Hydraumatics General Dealers newsletter\" (Newsletter terms and Privacy notice)."),
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("../EMAILS.md", import.meta.url), render());
  console.log("EMAILS.md written");
}
